public class DataTypes {
    public static void main(String[] args) {
        byte b = 10;
        short s = 1000;
        int i = 100000;
        long l = 10000000000L;
        float f = 10.5f;
        double d = 20.55;
        char c = 'J';
        boolean flag = true;

        System.out.println(b + " " + s + " " + i + " " + l);
        System.out.println(f + " " + d + " " + c + " " + flag);
    }
}
